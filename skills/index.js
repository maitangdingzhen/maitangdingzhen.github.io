// 意图分类器 — 根据用户消息和当前 Agent 路由到最匹配的专业 Agent
// ============================================================
export function classifyIntent(message, currentAgent = 'travel_planner') {
  // 兜底：null/undefined 时使用默认 Agent
  if (!currentAgent) currentAgent = 'travel_planner';
  const msg = message.trim();

  // 极短消息保持当前 Agent，避免频繁切换
  if (msg.length <= 1) return currentAgent;
  if (/^(好的|行|嗯|哦|谢谢|感谢|OK|ok|好滴|好嘞)$/.test(msg)) return currentAgent;

  // FAQ：价格、安全、退款、预订流程
  if (/价格|贵|便宜|多少钱|收费|费用|安全|保险|退款|退改|定金|怎么定|如何预订|预订流程|有优惠/.test(msg)) {
    return 'faq_handler';
  }

  // 旅拍：摄影、拍照、穿搭、机位
  if (/拍照|摄影|机位|穿搭|出片|复古|日系|情绪|胶片|写真|照片|怎么拍|哪里拍|拍.*照|风格/.test(msg)) {
    return 'photo_advisor';
  }

  // 小众推荐：景点、好玩、推荐、打卡、秘境
  if (/好玩|推荐|景点|小众|秘境|打卡|哪里|有什么|还有什么|还有啥|好逛|值得去|必去/.test(msg)) {
    return 'spot_recommender';
  }

  // 案例展示：案例、做过、客户、成功案例、别人
  if (/案例|做过|客户|成功|之前.*人|别人.*你们|你们.*过/.test(msg)) {
    return 'case_storyteller';
  }

  // 销售转化：满意、喜欢方案、加微信、联系、下单、预订
  if (/微信|加.*微信|联系|下单|预订|方案不错|很喜欢|挺好的|不错.*方案|可以.*定|怎么联系|留.*方式/.test(msg)) {
    return 'sales_closer';
  }

  // 问候/开场
  if (/你好|hi|hello|嗨|在吗|哈喽/.test(msg)) {
    return 'travel_planner';
  }

  // 默认：路线规划师（能力最通用）
  return 'travel_planner';
}

